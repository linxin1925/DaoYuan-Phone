import fs from 'node:fs';
import assert from 'node:assert/strict';
const ui=fs.readFileSync(new URL('../src/ui/renderUi.ts',import.meta.url),'utf8');
const runtime=fs.readFileSync(new URL('../src/index.ts',import.meta.url),'utf8');
assert.match(ui,/forumPosts\]\.sort\(\(a,b\)=>b\.createdAt\.localeCompare\(a\.createdAt\)\)/,'forum newest first');
assert.match(ui,/newsPapers\]\.sort\(\(a,b\)=>b\.createdAt\.localeCompare\(a\.createdAt\)\)/,'news newest first');
assert.match(ui,/fullContent:true/,'forum detail renders full content');
assert.match(ui,/selected\.comments/,'forum detail renders comments');
assert.match(ui,/news\.editorNote/,'newspaper renders editor note');
assert.match(ui,/news\.articles\.forEach/,'newspaper renders all articles');
assert.match(runtime,/VARIABLE_UPDATE_STARTED/,'auto generation remains on MVU update start');
assert.match(runtime,/forumAutoInterval/,'forum independent interval');
assert.match(runtime,/newsAutoInterval/,'news independent interval');
console.log('forum/news UI contract passed: newest-first / detail / comments / newspaper / MVU trigger');
