import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const source = readFileSync(new URL('./package-candidate.mjs', import.meta.url), 'utf8');
const start = source.indexOf('  const installPrompt=');
const end = source.indexOf('  globalThis.__daoyuanConfigureContentPresentationV12=', start);
assert.ok(start > 0 && end > start);
const listeners = new Map();
const active = new Map();
const state = { bodyPromptEnabled: false, ticketPromptEnabled: false };
const context = vm.createContext({ state, listeners, active, console });
vm.runInContext(`
  const window={addEventListener(){},removeEventListener(){}};
  const tavern_events={GENERATION_AFTER_COMMANDS:'generate',GENERATION_ENDED:'end',GENERATION_STOPPED:'stop',CHAT_CHANGED:'chat'};
  const eventOn=(name,fn)=>{if(!listeners.has(name))listeners.set(name,new Set());listeners.get(name).add(fn);return {stop(){listeners.get(name).delete(fn);}};};
  const uninjectPrompts=ids=>{if(!Array.isArray(ids))throw Error('IDs must be array');ids.forEach(id=>active.delete(id));};
  const injectPrompts=(prompts)=>{prompts.forEach(p=>active.set(p.id,p));return {uninject(){prompts.forEach(p=>active.delete(p.id));}};};
  const apiScope=()=>window, runtimeScopes=()=>[window], tavernEvents=()=>({}), read=()=>state;
  const bodyPrompt='<content>', ticketPrompt='<ShopReceipt> <QuestBoard>';
  ${source.slice(start,end)}
  globalThis.start=installPrompt;
`, context);
context.start();
context.start();
assert.equal(listeners.get('generate').size, 1, 'Repeated configuration must not duplicate listeners');
const emit=(name,...args)=>{for(const fn of listeners.get(name))fn(...args);};
emit('generate','normal',{},false);
assert.equal(active.size,0);
state.ticketPromptEnabled=true;
emit('generate','normal',{},false);
assert.equal(active.size,1);
assert.match(active.get('daoyuan-ticket-format-v12').content,/ShopReceipt.*QuestBoard/);
emit('end');
assert.equal(active.size,0);
state.bodyPromptEnabled=true;
emit('generate','normal',{},true);
assert.equal(active.size,0,'Dry runs must not inject');
emit('generate','normal',{},false);
assert.equal(active.size,2);
emit('chat');
assert.equal(active.size,0);
state.ticketPromptEnabled=false;
emit('generate','normal',{},false);
assert.equal(active.size,1);
assert.ok(active.has('daoyuan-body-format-v12'));
context.__daoyuanContentFormatPromptV12.destroy();
assert.equal(active.size,0);
assert.ok([...listeners.values()].every(set=>set.size===0));
console.log('Content injection: lexical APIs, independent toggles, repeat setup, dry-run, chat cleanup and destruction passed');
