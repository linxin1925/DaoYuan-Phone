export function earthNpcApparentAge(age, system) {
  if (age == null) return '无法判断';
  if (age <= 35) return `约${age}岁`;
  const value = String(system);
  if (/筑基|三级|三环|四级|四环|五级|五环/.test(value)) return '约二十四至二十八岁';
  if (/二级|二环|炼气后期/.test(value)) return '约二十五至三十二岁';
  if (/一级|一环|炼气初期|炼气中期/.test(value)) return '约二十八至三十五岁';
  return '与实际年龄相近';
}

