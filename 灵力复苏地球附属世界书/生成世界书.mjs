// Keep ordinary lore entries disabled and route them through getwi.  The
// special EJS entries must execute under both legacy inverted-enable mode and
// the current enable semantics, so they carry the extension's explicit
// portability decorator instead of depending on a player setting.
const portableEjsEntries = ejsEntries.map((entry) => {
  if (!entry.content.startsWith('@@generate_before\n')) {
    throw new Error(`${entry.comment} 缺少 @@generate_before 装饰器`);
  }
  return {
    ...entry,
    content: entry.content.replace('@@generate_before\n', '@@generate_before\n@@always_enabled\n'),
  };
});

entries.push(...portableEjsEntries);

